    private void loadDoanhThu() {
        tableModel.setRowCount(0);
        List<PhieuThue> list = phieuThueDAO.selectPhieuDaThanhToan();
        
        double tongDoanhThu = 0;
        
        for (PhieuThue pt : list) {
            tableModel.addRow(new Object[]{
                pt.getMaPhieu(),
                pt.getMaKH(),
                pt.getNgayThue() != null ? sdf.format(pt.getNgayThue()) : "",
                pt.getNgayTraThucTe() != null ? sdf.format(pt.getNgayTraThucTe()) : "",
                String.format("%,.0f VNĐ", pt.getTongTien())
            });
            
            // Cộng dồn tổng tiền
            tongDoanhThu += pt.getTongTien();
        }
        
        // Ghi ra TextField
        txtTongDoanhThu.setText(String.format("%,.0f VNĐ", tongDoanhThu));
    }

